"""Agent Rapporteur — incident report writer and webhook notifier.

Writes, for every confirmed incident:

    /reports/incident-<UTCstamp>-<ip>.md    human-readable report
    /reports/incident-<UTCstamp>-<ip>.json  the full alert payload

then POSTs that payload to the human-in-the-loop controller on the hypervisor
(http://192.168.122.1:5000/alert). The controller is the only component allowed
to touch `virsh`; the `proposed_commands` field below is advisory text for the
operator's terminal, never executed by the receiver.

Delivery policy: 5xx and connection errors are retried with exponential
backoff; 4xx are not (the payload will never become valid). A webhook failure
never aborts the pipeline: the report on disk is the durable trace.
"""

from __future__ import annotations

import json
import logging
import os
import random
import re
import time
from datetime import datetime, timezone
from pathlib import Path

import requests

from agent_detecteur import Alert

LOG = logging.getLogger("agent.rapporteur")

SOURCE = "kvm-sentinel-soc/agents"


def utc_stamp() -> str:
    return datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")


def stamp_from_iso(iso: str) -> str:
    try:
        parsed = datetime.fromisoformat(iso.replace("Z", "+00:00"))
        return parsed.astimezone(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    except ValueError:
        return utc_stamp()


def safe_token(value: str) -> str:
    """Only allow characters that cannot escape a filename."""
    return re.sub(r"[^0-9A-Za-z._-]", "_", value)[:64] or "unknown"


class AgentRapporteur:
    def __init__(
        self,
        reports_dir: str | Path,
        webhook_url: str,
        timeout_seconds: int = 10,
        token: str = "",
    ) -> None:
        self.reports_dir = Path(reports_dir)
        self.webhook_url = webhook_url
        self.timeout = timeout_seconds
        self.token = token
        self.session = requests.Session()

    # ------------------------------------------------------------------- files
    def build_markdown(self, alert: Alert) -> str:
        usernames = ", ".join(alert.usernames) or "unknown"
        mitre = ", ".join(alert.mitre_techniques) or "n/a"
        actions = "\n".join(f"- `{action}`" for action in alert.recommended_actions) or "- none"
        commands = "\n".join(f"    {command}" for command in self.proposed_commands(alert))
        confidence = (
            "heuristic (LLM unavailable)"
            if "heuristic" in alert.summary.lower()
            else "LLM assessment (Ollama/NVIDIA NIM)"
        )

        return f"""# SSH Brute-Force Incident — {alert.attacker_ip}

| field | value |
|---|---|
| alert id | `{alert.alert_id}` |
| detected at (UTC) | {alert.detected_at} |
| rule | `{alert.rule}` |
| severity | **{alert.severity_label.upper()}** ({alert.severity_score}/10) |
| technique | {mitre} |
| assessment source | {confidence} |

## Executive summary

{alert.summary}

## Detection evidence

| metric | value |
|---|---|
| attacker IP | `{alert.attacker_ip}` |
| failed authentications | {alert.failure_count} |
| sliding window | {alert.window_seconds} s |
| threshold | {alert.threshold} |
| targeted accounts | {usernames} |
| first seen (UTC) | {alert.first_seen} |
| last seen (UTC) | {alert.last_seen} |

## AI analyst assessment

{alert.analysis_markdown}

## MITRE ATT&CK

{mitre}

## Recommended actions

{actions}

## Hypervisor remediation (pending human approval)

The host controller asks the operator for confirmation before running:

```
{commands}
```

## Timeline of sampled events

| timestamp (UTC) | username | event |
|---|---|---|
{self._timeline_rows(alert)}

---
*Generated by KVM-Sentinel-SOC — agent pipeline on vm-soc. This report is
evidence, not an automated verdict: containment always requires a human `y`.*
"""

    @staticmethod
    def _timeline_rows(alert: Alert) -> str:
        rows = [
            f"| {alert.first_seen} | {', '.join(alert.usernames) or 'unknown'} | first failure in window |",
            f"| {alert.last_seen} | {', '.join(alert.usernames) or 'unknown'} | threshold reached |",
        ]
        if "successful" in alert.summary.lower():
            rows.append(f"| {alert.detected_at} | root | **successful authentication observed** |")
        return "\n".join(rows)

    def proposed_commands(self, alert: Alert) -> list[str]:
        snapshot = f"forensic-breach-{stamp_from_iso(alert.detected_at)}"
        return [
            f'virsh snapshot-create-as --domain vm-honeypot --name {snapshot} '
            f'--description "AI SOC Automated Snapshot" --atomic',
            "virsh domif-setlink vm-honeypot 52:54:00:10:10:01 down",
        ]

    def build_payload(self, alert: Alert, report_path: str) -> dict:
        payload = alert.model_dump()
        payload.update(
            {
                "vm": "vm-honeypot",
                "source": SOURCE,
                "proposed_commands": self.proposed_commands(alert),
                "report_path": report_path,
            }
        )
        return payload

    def _write_atomic(self, path: Path, content: str) -> None:
        tmp = path.with_suffix(path.suffix + ".tmp")
        tmp.write_text(content, encoding="utf-8")
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)

    # ----------------------------------------------------------------- webhook
    def deliver(self, payload: dict) -> dict:
        headers = {"Content-Type": "application/json", "User-Agent": SOURCE}
        if self.token:
            headers["X-Sentinel-Token"] = self.token

        attempts = 0
        last_error = None
        for attempt in range(4):
            attempts = attempt + 1
            try:
                response = self.session.post(
                    self.webhook_url, json=payload, headers=headers, timeout=self.timeout
                )
            except requests.RequestException as exc:
                last_error = str(exc)
                LOG.warning("webhook attempt %s failed: %s", attempts, exc)
            else:
                if 200 <= response.status_code < 300:
                    return {"delivered": True, "status": response.status_code, "attempts": attempts, "error": None}
                if 400 <= response.status_code < 500:
                    LOG.error("webhook rejected the payload (HTTP %s): %s",
                              response.status_code, response.text[:200])
                    return {
                        "delivered": False,
                        "status": response.status_code,
                        "attempts": attempts,
                        "error": response.text[:200],
                    }
                last_error = f"HTTP {response.status_code}"
                LOG.warning("webhook attempt %s returned %s", attempts, response.status_code)

            if attempt < 3:
                time.sleep((2 ** attempt) + random.uniform(0.0, 0.5))

        return {"delivered": False, "status": None, "attempts": attempts, "error": last_error}

    # ------------------------------------------------------------------ publish
    def publish(self, alert: Alert) -> dict:
        self.reports_dir.mkdir(parents=True, exist_ok=True)
        stamp = stamp_from_iso(alert.detected_at)
        base = f"incident-{stamp}-{safe_token(alert.attacker_ip)}"

        markdown_path = self.reports_dir / f"{base}.md"
        json_path = self.reports_dir / f"{base}.json"

        report_path = str(markdown_path)
        payload = self.build_payload(alert, report_path)

        try:
            self._write_atomic(markdown_path, self.build_markdown(alert))
            self._write_atomic(json_path, json.dumps(payload, indent=2, ensure_ascii=False) + "\n")
            LOG.info("report written: %s", markdown_path)
        except OSError as exc:
            LOG.error("could not write report in %s: %s", self.reports_dir, exc)

        delivery = self.deliver(payload)
        if delivery["delivered"]:
            LOG.info("webhook delivered to %s (HTTP %s)", self.webhook_url, delivery["status"])
        else:
            LOG.warning("webhook NOT delivered after %s attempt(s): %s",
                        delivery["attempts"], delivery["error"])

        return {
            "report_md": str(markdown_path),
            "report_json": str(json_path),
            "webhook": delivery,
        }
